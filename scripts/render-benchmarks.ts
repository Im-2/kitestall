// Generates docs/BENCHMARKS.md from docs/bench/*.json. Never hand-edit the output.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const rd = (f: string) => (existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : null);
const pct = (x: number) => (x * 100).toFixed(1) + "%";

export function renderBenchmarks() {
  const a = rd("docs/bench/adversarial.json");
  const b = rd("docs/bench/latency.json");
  const L: string[] = ["# Benchmarks (generated — do not edit by hand)", "", "Generated by `scripts/adversarial.ts` and `scripts/bench.ts` against the live SERV API. Testnet/demo build.", ""];
  if (a) {
    L.push(`## Adversarial suite (${a.generated_at})`, "",
      `Model: \`${a.model}\` with Prompt Guard on every request. Target: Nomad Desk day pass, list ${a.list_cents}c, private floor ${a.floor_cents}c (floor shown here for audit of this test only). Each message was replayed for up to 3 rounds with an offer.`, "",
      "| Metric | Result |", "|---|---|",
      `| Attacks run | ${a.attacks} |`, `| Benign messages run | ${a.benign} |`,
      `| **Floor breaches** (ask < floor or ask rising) | **${a.floor_breaches}** |`,
      `| **Floor/cost/salt/prompt leaks in replies** | **${a.leaks}** |`,
      `| Prompt Guard block rate on attacks | ${pct(a.attack_block_rate)} |`,
      `| Prompt Guard false-positive rate on benign | ${pct(a.benign_false_positive_rate)} |`,
      `| Rounds where SERV decided (attacks / benign) | ${a.live_rounds_attacks} / ${a.live_rounds_benign} |`,
      `| Rounds that used the deterministic fallback (attacks / benign) | ${a.fallback_rounds_attacks} / ${a.fallback_rounds_benign} |`, "",
      "Fallback reasons: " + (Object.entries(a.fallback_reasons ?? {}).map(([k, v]) => `${v}x ${k}`).join("; ") || "none"), "",
      "Note: attacks not blocked by Prompt Guard are still contained by code (clamps + leak filter); the table below shows the lowest ask reached in each.", "",
      "| Category | Attacks | Blocked by Prompt Guard |", "|---|---|---|");
    for (const [k, v] of Object.entries(a.by_category as Record<string, { n: number; blocked: number }>)) L.push(`| ${k} | ${v.n} | ${v.blocked} |`);
    L.push("", "<details><summary>Unblocked attacks and lowest ask reached</summary>", "", "| Category | Message | Lowest ask (cents) |", "|---|---|---|");
    for (const u of a.unblocked_attacks_lowest_ask) L.push(`| ${u.cat} | ${String(u.msg).replace(/\|/g, "\\|").replace(/\n/g, " ")} | ${u.lowest_ask_cents} |`);
    L.push("", "</details>", "");
    if (a.leak_examples.length) { L.push("### Leak findings", ""); for (const e of a.leak_examples) L.push(`- \`${String(e.msg).replace(/\n/g, " ")}\` → ${e.leaks.join(", ")}: "${e.reply}"`); L.push(""); }
  }
  if (b) {
    L.push(`## Latency and cost (${b.generated_at})`, "", "Cost is an estimate: token usage × catalog price (inference only; SERV feature surcharges are not in API responses).", "",
      "| Variant | n | p50 ms | p95 ms | mean tokens | est. $/call |", "|---|---|---|---|---|---|");
    for (const r of b.variants) L.push(`| ${r.name} | ${r.n} | ${r.p50} | ${r.p95} | ${r.mean_tokens} | ${r.mean_cost_usd} |`);
    L.push("", `Full 3-round negotiation (production config ${b.production.name}): p50 ${b.production.neg_p50} ms, p95 ${b.production.neg_p95} ms, mean est. cost $${b.production.neg_mean_cost_usd} per negotiation (n=${b.production.neg_n}).`, "");
  }
  writeFileSync("docs/BENCHMARKS.md", L.join("\n"));
}
if (process.argv[1]?.endsWith("render-benchmarks.ts")) renderBenchmarks();
